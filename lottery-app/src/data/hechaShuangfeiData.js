// ============================================================
// 【算法锁定】和差双飞组号：用双飞对（组选）组出当期号码
// 规则：三位号码（组选形式a<=b<=c）的任意一个数字对包含在双飞对中即入选
// 双飞以组选形式使用：双飞19 = 号码中同时含1和9（不分位置顺序）
// 全量8651期验证：开奖号至少含对应和差一个双飞对的比例75.9%
// 返回组选形式号码列表（升序）
// 禁止：改变入选规则；改用直选形式
// ============================================================
export function genZuXuanFromHeCha(hechaValue) {
  const pairs = hechaShuangFeiData[hechaValue];
  if (!pairs) return [];
  const pairSet = new Set(pairs);
  const mkPair = (x, y) => (x <= y ? `${x}${y}` : `${y}${x}`);
  const result = [];
  for (let a = 0; a <= 9; a++) {
    for (let b = a; b <= 9; b++) {
      for (let c = b; c <= 9; c++) {
        if (pairSet.has(mkPair(a, b)) || pairSet.has(mkPair(a, c)) || pairSet.has(mkPair(b, c))) {
          result.push(`${a}${b}${c}`);
        }
      }
    }
  }
  return result;
}
