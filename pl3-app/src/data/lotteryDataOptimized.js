// 解析紧凑数据为对象数组
function parseCompactData() {
  return COMPACT_DATA.split('\n').map(line => {
    const [issue, d1, d2, d3] = line.split(',');
    return { issue, d1: Number(d1), d2: Number(d2), d3: Number(d3) };
  });
}

